#include <algorithm>
#include <map>
#include <sstream>
#include <stdexcept>

namespace clutch {
namespace {
/// Encode a DOT label/path while rejecting unsupported control characters.
std::string quoted(const std::string &value) {
  std::string result = "\"";
  for (const unsigned char character : value) {
    switch (character) {
    case '\\':
    case '"':
      result += '\\';
      result += static_cast<char>(character);
      break;
    case '\n':
      result += "\\n";
      break;
    case '\r':
      result += "\\r";
      break;
    case '\t':
      result += "\\t";
      break;
    default:
      if (character < encoding::first_printable_ascii ||
          character == encoding::ascii_delete)
        throw std::runtime_error("unsupported control character in graph path");

      result += static_cast<char>(character);
    }
  }

  return result + '"';
}
}  // namespace

/// Export compile/link edges for inspection without launching Graphviz.
void write_graph_visualization(const Graph &graph) {
  std::ostringstream dot;
  dot << "// Generated by Clutch. Edges point from prerequisites to outputs.\n"
         "// Compiler-discovered headers are not included.\n"
         "digraph clutch {\n  rankdir=LR;\n  node [fontname=\"sans-serif\"];\n"
      << "  label=" << quoted("Clutch: " + graph.project.name) << ";\n";
  std::map<fs::path, size_t> nodes;
  // Intern shared paths once; relative labels stay readable and tooltips stay
  // exact.
  const auto node = [&](const fs::path &path,
                        const char *const shape,
                        const char *const color) {
    const auto [entry, inserted] = nodes.emplace(path, nodes.size());
    if (inserted) {
      const auto relative = path.lexically_relative(graph.project.root);
      dot << "  n" << entry->second << " [label="
          << quoted((relative.empty() ? path : relative).generic_u8string())
          << ", tooltip=" << quoted(path.generic_u8string())
          << ", shape=" << shape << ", color=" << quoted(color) << "];\n";
    }

    return entry->second;
  };

  // Inputs point to their produced objects, which point to the linked
  // executable.
  for (const auto &target : graph.targets) {
    const auto output = node(target.output, "doubleoctagon", "forestgreen");
    for (const auto &prefix : target.precompiled_headers) {
      const auto artifact = node(prefix.creator.object, "ellipse", "purple");
      for (const auto &header : prefix.headers) {
        const auto input = node(header, "box", "slategray");
        dot << "  n" << input << " -> n" << artifact
            << " [label=\"precompile\"];\n";
      }
    }
    for (const auto dependency : target.dependencies) {
      const auto provider = node(graph.targets.at(dependency).output,
                                 "doubleoctagon",
                                 "forestgreen");
      dot << "  n" << provider << " -> n" << output
          << " [label=\"target dependency\"];\n";
    }
    for (const auto &input : target.link_inputs) {
      const auto library = node(input, "ellipse", "forestgreen");
      dot << "  n" << library << " -> n" << output
          << " [label=\"imported library\"];\n";
    }
    for (const auto &unit : target.units) {
      const auto &[source, object, arguments] = unit;
      (void)arguments;
      const auto input = node(source, "box", "slategray");
      const auto intermediate = node(object, "ellipse", "steelblue");
      if (const auto *const prefix = pch::for_unit(target, unit)) {
        const auto artifact = node(prefix->creator.object, "ellipse", "purple");
        dot << "  n" << artifact << " -> n" << intermediate
            << " [label=\"PCH\"];\n";
      }
      dot << "  n" << input << " -> n" << intermediate
          << " [label=\"compile\"];\n"
          << "  n" << intermediate << " -> n" << output << " [label=\""
          << (target.type == TargetType::StaticLibrary ? "archive" : "link")
          << "\"];\n";
    }
  }

  // Upstream executors own their internal graph; expose their artifact
  // boundary.
  for (const auto &build : graph.project.foreign_builds) {
    const auto action_id = "foreign:" + build.id;
    dot << "  " << quoted(action_id)
        << " [shape=box, label=\"native dependency build\"];\n";
    for (const auto &artifact : build.artifacts) {
      const auto output = node(artifact, "ellipse", "forestgreen");
      dot << "  " << quoted(action_id) << " -> n" << output
          << " [label=\"build\"];\n";
    }
    for (const auto &target : graph.targets) {
      if (std::find(target.foreign_dependencies.begin(),
                    target.foreign_dependencies.end(),
                    build.id) == target.foreign_dependencies.end())
        continue;

      for (const auto &unit : target.units) {
        const auto output = node(unit.object, "ellipse", "steelblue");
        dot << "  " << quoted(action_id) << " -> n" << output
            << " [label=\"prepare headers\"];\n";
      }
      for (const auto &prefix : target.precompiled_headers) {
        const auto output = node(prefix.creator.object, "ellipse", "purple");
        dot << "  " << quoted(action_id) << " -> n" << output
            << " [label=\"prepare headers\"];\n";
      }
    }
  }

  // Logical package edges include header-only imports with no native target.
  for (const auto &package : graph.project.packages) {
    dot << "  " << quoted(package.id) << " [shape=folder, label="
        << quoted(dependencies::identity(package) + " @ " + package.version)
        << "];\n";
    for (const auto &dependency : package.dependencies)
      dot << "  " << quoted(dependency) << " -> " << quoted(package.id)
          << " [label=\"package\"];\n";
  }

  dot << "}\n";
  write_if_changed(graph.project.build / layout::build_graph, dot.str());
}
}  // namespace clutch
