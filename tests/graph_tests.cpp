/**
 * @file
 * @brief Check cycle/duplicate-output rejection, shared inputs and DOT
 * serialization.
 *
 * CTest supplies an artifact directory and optionally Graphviz's dot
 * executable. Rendering is optional; structural and safety checks always run
 * without Graphviz.
 */

#include "core/build_graph.hpp"
#include "core/graph_visualization.hpp"
#include "platform/process.hpp"

#include <chrono>
#include <cstdio>
#include <fstream>
#include <iostream>
#include <iterator>
#include <stdexcept>

namespace
{
    /// Report an invariant violation through the test program's common error
/// handler.
    void require(const bool condition, const char* message)
    {
        if (!condition)
            throw std::runtime_error(message);
    }

    /// Require graph validation to fail for the intended reason, not an unrelated
/// one.
    void rejects(const clutch::Graph& graph, const std::string& expected)
    {
        try
        {
            clutch::validate_build_graph(graph);
        }
        catch (const std::runtime_error& error)
        {
            require(std::string(error.what()).find(expected) != std::string::npos,
                    "graph rejected for an unexpected reason");
            return;
        }

        throw std::runtime_error("invalid graph was accepted");
    }

    /// Read generated bytes exactly for escaping and deterministic-output
/// assertions.
    std::string read(const clutch::fs::path& path)
    {
        if (std::ifstream input(path, std::ios::binary); input)
            return {std::istreambuf_iterator(input), {}};

        throw std::runtime_error("cannot read graph test output");
    }
} // namespace

/// Exercise graph safety and serialization, optionally rendering with real dot.
// The test body catches every exception below. LLVM's MSVC fstream analysis
// still reports codecvt::bad_cast as escaping through those catch handlers.
// NOLINTNEXTLINE(bugprone-exception-escape)
int main(const int argc, char** argv)
{
    try
    {
        require(argc >= 2, "expected graph test artifact directory");
        const auto unique =
            std::chrono::steady_clock::now().time_since_epoch().count();
        const auto root = clutch::fs::absolute(argv[1]) / std::to_string(unique);
        const auto build = root / "build with spaces";
        const auto source = root / "source \"quoted\" shared.cpp";
        clutch::Graph graph;
        graph.project.root = root;
        graph.project.build = build;
        graph.project.name = "graph \"escaping\" \\ test";
        graph.targets = {
            {
                "app",
                build / "app",
                {{source, build / "app.o", {"compiler"}}},
                {"linker"}
            },
            {
                "test",
                build / "test",
                {{source, build / "test.o", {"compiler"}}},
                {"linker"}
            }
        };
        clutch::validate_build_graph(graph);

        // Mutate one invariant at a time, retaining a known-valid shared-source
        // graph.
        auto invalid = graph;
        invalid.targets[1].units[0].object = invalid.targets[0].units[0].object;
        rejects(invalid, "multiple build commands");
        invalid = graph;
        invalid.targets[0].units[0].source = invalid.targets[0].output;
        rejects(invalid, "dependency cycle");
        invalid = graph;
        invalid.targets[0].units[0].source = invalid.targets[1].output;
        invalid.targets[1].units[0].source = invalid.targets[0].output;
        rejects(invalid, "dependency cycle");
        invalid = graph;
        invalid.targets[0].output = invalid.targets[1].output;
        rejects(invalid, "multiple build commands");
        invalid = graph;
        invalid.targets[0].units.clear();
        rejects(invalid, "no compilation or link commands");
        invalid = graph;
        invalid.targets[0].units[0].arguments.clear();
        rejects(invalid, "no compiler command");

        // Check serialized escaping/edges and ensure unchanged output keeps its
        // mtime.
        clutch::write_graph_visualization(graph);
        const auto path = build / "build-graph.dot";
        const auto text = read(path);
        require(text.find("\\\"quoted\\\"") != std::string::npos,
                "DOT quote escaping missing");
        require(text.find("\\\\ test") != std::string::npos,
                "DOT backslash escaping missing");
        size_t edges = 0;
        for (auto position = text.find(" -> "); position != std::string::npos;
             position = text.find(" -> ", position + 4))
            ++edges;

        require(edges == 4, "DOT omitted or duplicated build edges");
        const auto timestamp = clutch::fs::last_write_time(path);
        clutch::write_graph_visualization(graph);
        require(read(path) == text &&
                clutch::fs::last_write_time(path) == timestamp,
                "unchanged DOT output was rewritten");

        // Rendering supplements structural checks when Graphviz was found by CMake.
        if (argc >= 3)
        {
            const auto output = build / "build-graph.svg";
            require(
                clutch::run({argv[2], "-Tsvg", path.string(), "-o", output.string()},
                            root) == 0,
                "Graphviz rejected the generated DOT");
            require(read(output).find("<svg") != std::string::npos,
                    "Graphviz produced no SVG");
        }
        else
        {
            std::cout << "Graphviz not found: rendering check skipped\n";
        }

        std::cout << "PASS: DAG validation, shared inputs, DOT escaping and "
            "deterministic output\n";
        return 0;
    }
    catch (const std::exception& error)
    {
        std::cerr << "graph test failed: " << error.what() << '\n';
        return 1;
    }
    catch (...)
    {
        std::fputs("graph test failed: unknown exception\n", stderr);
        return 1;
    }
}
